def web_translations(root, language):
    language = language if language in ('ru', 'en') else 'ru'
    result = json.loads((Path(root) / f'sff/locales/webui_{language}.json').read_text(encoding='utf-8'))
    result.update(STRINGS if language == 'en' else {english: russian for russian, english in STRINGS.items()})
    return result
